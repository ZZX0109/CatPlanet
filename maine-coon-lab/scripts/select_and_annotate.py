selected=ROOT/'references/selected';selected.mkdir(exist_ok=True)
final=[]
for index,(candidate_id,(view,observation)) in enumerate(notes.items(),1):
    row=rows[candidate_id]
    source=ROOT/row['local_path']
    target=selected/f'{index:02d}{source.suffix}'
    shutil.copy2(source,target)
    final.append({**row,'reference_id':index,'local_path':str(target.relative_to(ROOT)),'view':view,'observation_zh':observation})
assert len({r['sha256'] for r in final})==50
(ROOT/'references/selected-50.json').write_text(json.dumps(final,ensure_ascii=False,indent=2))

